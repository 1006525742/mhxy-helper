# 预解析成扁平 64 列表，顺序与 board 下标一致
_COORDS = []
for _row_idx, _row in enumerate(_HE):
    for _col_idx, _cell in enumerate(_row):
        if _cell is None:
            _COORDS.append(None)
        else:
            _name, _x, _y = _cell.split("|")
            _COORDS.append(
                {
                    "action": _row_idx * 8 + _col_idx,
                    "row": _row_idx,
                    "column": _col_idx,
                    "mapName": _name,
                    "x": int(_x),
                    "y": int(_y),
                }
            )


def get_coordinate(index: int) -> dict | None:
    """ge(index)：棋盘格下标 -> 地图坐标 {mapName,x,y,row,column,action} 或 None。"""
    if not isinstance(index, int) or index < 0 or index >= len(_COORDS):
        return None
    return _COORDS[index]


def coordinate_label(coord: dict | None) -> str:
    """坐标 -> 人类可读字符串，如 '长寿村（31, 24）'；无则 '无地点信息'。"""
    if not coord:
        return "无地点信息"
    return f"{coord['mapName']}（{coord['x']}, {coord['y']}）"


